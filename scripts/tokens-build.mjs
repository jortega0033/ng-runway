#!/usr/bin/env node
// Regenerates tokens/tailwind-theme.css and tokens/tokens.ts from tokens/tokens.css + tokens/tokens.json.
// Usage: node scripts/tokens-build.mjs [--check]
// Plain Node, no dependencies. Works on Windows, macOS and Linux.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokensDir = join(root, 'tokens');

/** Parse tokens.css into { root, light, dark } maps of custom property -> raw value. */
export function parseCss(css) {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = { root: {}, light: {}, dark: {} };
  const blockRe = /:root(\.theme-light|\.theme-dark)?\s*\{([^}]*)\}/g;
  for (const m of clean.matchAll(blockRe)) {
    const key = m[1] === '.theme-light' ? 'light' : m[1] === '.theme-dark' ? 'dark' : 'root';
    for (const d of m[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[key][d[1]] = d[2].trim();
  }
  return out;
}

/** Resolve var(--x) chains for a theme (theme map first, then :root). */
export function resolveVar(value, maps, seen = new Set()) {
  const m = /^var\((--[\w-]+)(?:\s*,\s*(.+))?\)$/.exec(value);
  if (!m) return value;
  const name = m[1];
  if (seen.has(name)) throw new Error(`Circular token reference: ${name}`);
  seen.add(name);
  const next = maps.find((map) => name in map)?.[name];
  if (next === undefined) {
    if (m[2] !== undefined) return m[2].trim();
    throw new Error(`Unresolved token reference: ${name}`);
  }
  return resolveVar(next, maps, seen);
}

/** Resolve a `{a.b.c}` reference in tokens.json. */
export function resolveRef(json, value) {
  const m = /^\{(.+)\}$/.exec(value);
  if (!m) return value;
  let node = json;
  for (const part of m[1].split('.')) node = node?.[part];
  if (!node || node.$value === undefined) throw new Error(`Unresolved JSON reference: ${value}`);
  return resolveRef(json, node.$value);
}

/** Semantic colors of one theme as { 'background-hover': '#968c5512', foreground: '...' }. */
export function cssSemanticColors(parsed, theme) {
  const out = {};
  for (const [name, value] of Object.entries(parsed[theme])) {
    if (!name.startsWith('--colors-')) continue;
    out[name.slice('--colors-'.length)] = resolveVar(value, [parsed[theme], parsed.root]);
  }
  return out;
}

/** Same map built from tokens.json (`default` entries map to the group name). */
export function jsonSemanticColors(json, theme) {
  const out = {};
  for (const [group, entries] of Object.entries(json.theme[theme].color)) {
    for (const [name, token] of Object.entries(entries)) {
      const key = name === 'default' ? group : `${group}-${name}`;
      out[key] = resolveRef(json, token.$value);
    }
  }
  return out;
}

function flatData(node, prefix = []) {
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out[[...prefix, k].join('-')] = v.$value;
    else if (v && typeof v === 'object') Object.assign(out, flatData(v, [...prefix, k]));
  }
  return out;
}

const header = (file) =>
  `/* GENERATED by scripts/tokens-build.mjs from tokens/tokens.css + tokens/tokens.json. Do not edit.\n   Run: npm run tokens:build (${file}) */\n`;

export function build(dir = tokensDir) {
  const css = readFileSync(join(dir, 'tokens.css'), 'utf8');
  const json = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));
  const parsed = parseCss(css);
  const light = cssSemanticColors(parsed, 'light');
  const dark = cssSemanticColors(parsed, 'dark');
  const names = Object.keys(light);

  // ---- tailwind-theme.css ------------------------------------------------
  const keep = (re) =>
    Object.entries(parsed.root)
      .filter(([k]) => re.test(k))
      .map(([k, v]) => `  ${k}: ${v};`);
  const data = flatData(json.data);
  const dataColors = Object.entries(data)
    .filter(([, v]) => typeof v === 'string' && /^#[0-9a-f]{3,8}$/i.test(v))
    .filter(([k]) => /^(entity-palette|absence|schedule)-/.test(k))
    .map(([k, v]) => `  --color-${k}: ${v};`);

  const tw = [
    header('tailwind-theme.css'),
    '/* Tailwind v4 theme. Semantic colors are aliases to the live CSS custom properties,',
    '   so utilities follow .theme-light / .theme-dark. Default Tailwind palette is removed. */',
    '@theme {',
    '  --color-*: initial;',
    '  --radius-*: initial;',
    '  --shadow-*: initial;',
    '  --text-*: initial;',
    '  --font-*: initial;',
    ...keep(
      /^--(text-|spacing$|breakpoint-|container-|max-width-|spacing-|shadow-|drop-shadow-|ease-|animate-|default-transition|aspect-|font-mono|font-weight-|tracking-|leading-)/,
    ).filter((l) => !/^ {2}--(shadow-tab-active|text-color-|text-size-inherit)/.test(l)),
    ...dataColors,
    '}',
    '',
    '@theme inline {',
    '  --font-sans: var(--font-family-sans);',
    '  --font-title: var(--font-family-title);',
    ...Object.keys(parsed.root)
      .filter((k) => /^--border-radius-/.test(k))
      .map((k) => `  --radius-${k.slice('--border-radius-'.length)}: var(${k});`),
    '  --radius-base: var(--radius-base);',
    '  --radius-3xl: var(--radius-3xl);',
    '  --radius-4xl: var(--radius-4xl);',
    '  --shadow-tab-active: var(--shadow-tab-active);',
    ...names.map((n) => `  --color-${n}: var(--colors-${n});`),
    '  --color-scrim: var(--background-color-scrim);',
    '}',
    '',
  ].join('\n');

  // ---- tokens.ts ---------------------------------------------------------
  const obj = (o) =>
    JSON.stringify(o, null, 2)
      .replace(/"([A-Za-z_$][\w$]*)":/g, '$1:')
      .replace(/"/g, "'");
  const chart = Object.fromEntries(
    Object.entries(json.data.chart)
      .filter(([k]) => !k.startsWith('$'))
      .map(([k, v]) => [k, { fallback: v.$value, cssVar: v.$extensions.cssVar }]),
  );
  const ts = [
    header('tokens.ts'),
    '/* eslint-disable */',
    `export const colorTokens = {\n  light: ${obj(light).replace(/\n/g, '\n  ')},\n  dark: ${obj(dark).replace(/\n/g, '\n  ')},\n} as const;`,
    '',
    `export const colorTokenNames = ${obj(names)} as const;`,
    '',
    'export type ColorToken = (typeof colorTokenNames)[number];',
    '',
    `export const dataTokens = ${obj({
      entityPalette: Object.entries(data)
        .filter(([k]) => k.startsWith('entity-palette-'))
        .map(([, v]) => v),
      absence: Object.fromEntries(
        Object.entries(data)
          .filter(([k]) => k.startsWith('absence-'))
          .map(([k, v]) => [k.slice('absence-'.length), v]),
      ),
      schedule: Object.fromEntries(
        Object.entries(data)
          .filter(([k]) => k.startsWith('schedule-'))
          .map(([k, v]) => [k.slice('schedule-'.length), v]),
      ),
      chart,
    })} as const;`,
    '',
    'export type AbsenceType = keyof typeof dataTokens.absence;',
    '',
  ].join('\n');

  return { 'tailwind-theme.css': tw, 'tokens.ts': ts };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [file, content] of Object.entries(build())) {
    const path = join(tokensDir, file);
    if (check) {
      let current = '';
      try {
        current = readFileSync(path, 'utf8');
      } catch {
        /* missing */
      }
      if (current !== content) {
        console.error(`STALE: tokens/${file} (run npm run tokens:build)`);
        stale = true;
      }
    } else {
      writeFileSync(path, content);
      console.log(`wrote tokens/${file}`);
    }
  }
  if (stale) process.exit(1);
}
